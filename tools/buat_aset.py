def ke_rgba(hex_):
    hex_ = hex_.lstrip('#')
    return tuple(int(hex_[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def gambar(nama, baris):
    tinggi = len(baris)
    lebar = len(baris[0])
    img = Image.new('RGBA', (lebar, tinggi), (0, 0, 0, 0))
    for y, row in enumerate(baris):
        assert len(row) == lebar, f'{nama} baris {y}: lebar {len(row)} -> {row!r}'
        for x, ch in enumerate(row):
            warna = PALET[ch]
            if warna:
                img.putpixel((x, y), ke_rgba(warna))
    return img


def main():
    akar = Path(__file__).resolve().parent.parent
    keluar = akar / 'frontend' / 'src' / 'assets' / 'sprites'
    keluar.mkdir(parents=True, exist_ok=True)
    gambar_semua = {}
    for nama, baris in S.items():
        img = gambar(nama, baris)
        img.save(keluar / f'{nama}.png')
        gambar_semua[nama] = img

    # lembar pratinjau
    skala, kolom = 6, 8
    nama_list = list(gambar_semua)
    baris_n = (len(nama_list) + kolom - 1) // kolom
    lebar_sel = 16 * skala + 12
    tinggi_sel = 16 * skala + 26
    sheet = Image.new('RGB', (kolom * lebar_sel, baris_n * tinggi_sel), (236, 240, 236))
    dr = ImageDraw.Draw(sheet)
    for i, nama in enumerate(nama_list):
        cx, cy = (i % kolom) * lebar_sel + 6, (i // kolom) * tinggi_sel + 4
        g = gambar_semua[nama]
        besar = g.resize((g.width * skala, g.height * skala), Image.NEAREST)
        sheet.paste(besar, (cx, cy), besar)
        dr.text((cx, cy + 16 * skala + 4), nama, fill=(40, 40, 60))
    sheet.save(akar / 'tools' / 'pratinjau_aset.png')
    print(f'{len(nama_list)} sprite dibuat di {keluar}')


if __name__ == '__main__':
    main()
